class MotionPlan(BaseModel):
    model_config = ConfigDict(extra='forbid')
    version: Literal['motion-plan-v1'] = 'motion-plan-v1'
    source_signature: str
    seed: int = Field(default=42, ge=0, le=2147483647)
    cues: list[CuePlan]
    visual_language: VisualLanguage | None = None


def usable_lines(project):
    result = []
    for i, line in enumerate(project.get('lines', [])):
        start, end = line.get('start'), line.get('end')
        if not all(isinstance(t, (int, float)) and math.isfinite(t) for t in (start, end)) or start < 0 or end < start:
            raise ValueError(f'第 {i+1} 句歌词时间无效')
        if end == start: continue  # Alignment annotations are not animation cues.
        for word in line.get('words', []):
            ws, we = word.get('start'), word.get('end')
            if not all(isinstance(t, (int, float)) and math.isfinite(t) for t in (ws, we)) or ws < start-.05 or we > end+.05 or we < ws:
                raise ValueError(f'第 {i+1} 句字词时间无效')
        result.append((i, line))
    return result


def legacy_source_signature(project):
    timing = [{'index': i, 'text': line.get('text', ''), 'start': line['start'], 'end': line['end'], 'words': line.get('words', [])} for i, line in usable_lines(project)]
    return hashlib.sha256(json.dumps(timing, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def source_signature(project):
    # Layout references lyric structure; timing is always rebound from alignment.
    lyrics = [{'index': i, 'text': line.get('text', ''),
               'words': [word.get('word', '') for word in line.get('words', [])]}
              for i, line in usable_lines(project)]
    return 'lyrics-v1:' + hashlib.sha256(json.dumps(lyrics, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def validate_plan(project, data):
    plan = MotionPlan.model_validate(data)
    expected = {f'line_{i + 1:04d}': line for i, line in usable_lines(project)}
    current = source_signature(project)
    if plan.source_signature not in (current, legacy_source_signature(project)):
        # Old hashes contain timing. They can be migrated only when every line
        # carries enough text/index information to validate against current lyrics.
        legacy = bool(re.fullmatch(r'[0-9a-f]{64}', plan.source_signature))
        complete_text = all(
            cue.line_id in expected and (cue.poster or cue.groups) and
            ''.join(''.join(node.text.split()) for node in (cue.poster.nodes if cue.poster else cue.groups)) ==
            ''.join(expected[cue.line_id].get('text', '').split())
            for cue in plan.cues)
        if not legacy or not complete_text:
            raise ValueError('方案与当前歌曲的歌词或字词结构不匹配，请确认歌曲并重新生成导演输入；仅调整时间轴无需重新导演')
    ids = [cue.line_id for cue in plan.cues]
    if len(ids) != len(set(ids)) or set(ids) != set(expected):
        raise ValueError('导演方案必须完整覆盖每句有效歌词，且不能重复或引用不存在的句子')
    for cue in plan.cues:
        validate_cue(expected[cue.line_id], cue)
    plan.source_signature = current
    return plan


# Only presentation whitespace between Han characters is optional; English word boundaries remain.
_HAN = r'\u3400-\u9fff\uf900-\ufaff\U00020000-\U000323af'

def normalize_emphasis_text(text):
    text = ' '.join(text.split())
    return re.sub(rf'(?<=[{_HAN}]) (?=[{_HAN}])', '', text)


def emphasis_matches(text, emphasis):
    focus = normalize_emphasis_text(emphasis)
    return bool(focus) and focus in normalize_emphasis_text(text)


def normalize_match_text(text):
    return re.sub(r'[\s，。！？、；：”’“‘,\.!?;:\'"`—\-\u2014…~～]+', '', text).lower()


def validate_cue(line, cue):
    if cue.emphasis and not emphasis_matches(line.get('text', ''), cue.emphasis):
        raise ValueError(f'{cue.line_id} 的强调词不在歌词中')
    words = line.get('words', [])
    if cue.groups:
        indices = [i for group in cue.groups for i in group.word_indices]
        if indices != list(range(len(words))):
            raise ValueError('词组必须按原顺序完整覆盖字词索引，不能缺字、重复或重排')
        for group in cue.groups:
            text = ''.join(words[i].get('word', '') for i in group.word_indices)
            if ''.join(group.text.split()) != ''.join(text.split()):
                if normalize_match_text(group.text) != normalize_match_text(text):
                    raise ValueError(f'词组文字必须与引用的原始字词一致（期望：“{text.strip()}”，收到：“{group.text}”）')
            if group.emphasis and not emphasis_matches(group.text, group.emphasis):
                raise ValueError('词组强调词必须属于该词组')
    if cue.poster:
        nodes = cue.poster.nodes
        indices = [i for node in nodes for i in node.word_indices]
        if indices != list(range(len(words))):
            raise ValueError('海报文字必须按原顺序完整覆盖字词，不能缺字、重复或重排')
        if sum(node.role == 'primary' for node in nodes) != 1:
            raise ValueError('海报必须有且只有一个主视觉文字对象')
        for relation in cue.poster.relations:
            refs = relation.node_indices
            if len(set(refs)) != len(refs) or any(i < 0 or i >= len(nodes) for i in refs):
                raise ValueError('语义关系必须引用当前海报中存在且不重复的节点索引')
            if relation.kind in ('guidance', 'contrast') and len(refs) < 2:
                raise ValueError('引导和对照关系至少需要两个文字节点')
        for node in nodes:
            expected = ''.join(words[i].get('word', '') for i in node.word_indices) if words else line.get('text', '')
            if not words and len(nodes) != 1:
                raise ValueError('没有字词对齐时，海报只能使用一个整句文字对象')
            if ''.join(node.text.split()) != ''.join(expected.split()):
                if normalize_match_text(node.text) != normalize_match_text(expected):
                    raise ValueError(f'海报文字必须与引用的歌词一致，严禁翻译或替换（期望：“{expected.strip()}”，收到：“{node.text}”）')
            if node.beat_reaction != 'none' and node.role != 'primary':
                raise ValueError('拍点回弹只允许用于主视觉对象')
            if node.emphasis and not emphasis_matches(node.text, node.emphasis):
                raise ValueError(f'{cue.line_id} 的海报强调词“{node.emphasis}”必须来自对应文字对象“{node.text}”（中文间空白可忽略，英文词界须保留）')
    return cue


def compile_groups(line, cue):
    """LLM chooses references; only alignment supplies executable timing."""
    return [{**group.model_dump(), 'start': line['words'][group.word_indices[0]]['start'] if group.word_indices else line['start'],
             'end': line['words'][group.word_indices[-1]]['end'] if group.word_indices else line['end']} for group in (cue.poster.nodes if cue.poster else cue.groups)]



def cue_signature(plan, line_id):
    cue = next(cue for cue in plan.cues if cue.line_id == line_id)
    data = cue.model_dump()
    if data.get('poster') and data['poster'].get('visual_intensity') == 'auto':
        data['poster'].pop('visual_intensity', None)  # Existing plans keep their signatures.
    if data.get('poster') and data['poster'].get('semantic_mode') == 'auto':
        data['poster'].pop('semantic_mode', None)
    if data.get('poster') and not data['poster'].get('relations'):
        data['poster'].pop('relations', None)  # Preserve signatures for existing relation-free plans.
    return hashlib.sha256(json.dumps({'cue': data, 'seed': plan.seed}, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


class LineResponse(BaseModel):
    model_config = ConfigDict(extra='forbid')
    version: Literal['motion-line-response-v1'] = 'motion-line-response-v1'
    source_signature: str
    base_cue_signature: str | None
    cue: CuePlan


def line_response(project, data, line_id):
    response = LineResponse.model_validate(data)
    if response.source_signature not in (source_signature(project), legacy_source_signature(project)):
        raise ValueError('歌词或字词结构已变化，请重新获取单句提示词；仅调整时间轴无需重新导演')
    response.source_signature = source_signature(project)
    if response.cue.line_id != line_id:
        raise ValueError('返回方案只能修改请求的那一句歌词')
    lines = {f'line_{i+1:04d}': line for i, line in usable_lines(project)}
    if line_id not in lines: raise ValueError('歌词句子不存在')
    validate_cue(lines[line_id], response.cue)
    if lines[line_id].get('words') and not response.cue.groups and not response.cue.poster:
        raise ValueError('单句导演必须返回语义词组，至少一个词组完整覆盖全部字词')
    return response, compile_groups(lines[line_id], response.cue)


def director_input(project):
    analysis = project.get('analysis') or {}
    energy = analysis.get('energy_curve', [])
    beats = analysis.get('beats', [])
    rows = []
    for i, line in usable_lines(project):
        values = [float(row['energy']) for row in energy if line['start'] <= row['time'] < line['end']]
        text = line.get('text', '')
        han_chars = re.findall(rf'[{_HAN}]', text)
        latin_words = re.findall(r"[a-zA-Z0-9\u00C0-\u024F]+(?:['’\-][a-zA-Z0-9\u00C0-\u024F]+)*", text)
        duration = round(float(line['end'] - line['start']), 2)
        is_pure_western = len(han_chars) == 0 and len(latin_words) > 0

        if is_pure_western:
            units = len(latin_words)
            char_count = units
            clauses = [s.strip() for s in re.split(r'[,;—\-\u2014]+', text) if s.strip()]
            if units <= 3:
                target_nodes = 1
            elif 4 <= units <= 6:
                target_nodes = 2 if len(clauses) >= 2 or duration >= 3.0 else 1
            elif 7 <= units <= 10:
                target_nodes = 3 if len(clauses) >= 3 else 2
            else:
                target_nodes = 4 if len(clauses) >= 4 else 3
            suggested_segments = clauses if len(clauses) > 1 else []
        else:
            units = len(han_chars) + len(latin_words)
            char_count = units if units > 0 else len(re.sub(r'\s+', '', text))
            clauses = [s for s in re.split(r'\s+', text) if s]
            if units <= 4:
                target_nodes = 1
            elif 5 <= units <= 7:
                target_nodes = 2 if len(clauses) >= 2 else 1
            elif units == 8:
                target_nodes = 2
            elif units >= 14 and len(clauses) >= 4:
                target_nodes = 4
            elif units >= 9 or len(clauses) >= 3:
                target_nodes = 3
            else:
                target_nodes = 2
            suggested_segments = clauses if len(clauses) > 1 else []

        rows.append({'line_id': f'line_{i+1:04d}', 'text': text, 'start': line['start'], 'end': line['end'],
                     'duration': duration, 'char_count': char_count, 'target_nodes': target_nodes,
                     'suggested_segments': suggested_segments,
                     'words': [{**word, 'word_index': j} for j, word in enumerate(line.get('words', []))], 'section': line.get('section', ''),
                     'mean_energy': round(sum(values)/len(values), 3) if values else None,
                     'beats': [time for time in beats if line['start'] <= time < line['end']]})
    if not rows:
        raise ValueError('没有可用于动画的有效歌词时间段')
    return {'version': 'motion-input-v1', 'source_signature': source_signature(project), 'title': project.get('title', ''),
            'duration': project.get('duration', 0), 'bpm': analysis.get('bpm', 0), 'sections': project.get('sections', []),
            'analysis_limits': {key: value for key, value in analysis.get('metadata', {}).items() if key in ('downbeats_method', 'drum_hits_method', 'confidence_note', 'section_candidates_method')}, 'templates': TEMPLATES, 'lines': rows,
            'capabilities': director_capabilities(), 'output_schema': design_schema(MotionPlan)}


def rule_plan(project, previous=None, style='impact'):
    source = director_input(project)
    locked = {}
    if previous:
        locked = {cue.line_id: cue for cue in validate_plan(project, previous).cues if cue.locked}
    cues = []
    for i, line in enumerate(source['lines']):
        if line['line_id'] in locked:
            cues.append(locked[line['line_id']]); continue
        section = line['section'].lower()
        strong = 'chorus' in section or '副歌' in section or (line['mean_energy'] or 0) > .72
        quiet = 'outro' in section or '尾奏' in section or (line['mean_energy'] is not None and line['mean_energy'] < .25)
        template = 'quiet-hold' if quiet else 'word-impact' if strong and line['words'] else 'phrase-rise'
        cues.append(CuePlan(line_id=line['line_id'], template=template, layout='center' if strong or i % 2 == 0 else 'left',
                            palette=style, intensity=.8 if strong else .25 if quiet else .5))
    return MotionPlan(source_signature=source['source_signature'], seed=previous.get('seed', 42) if previous else 42, cues=cues,
                      visual_language=previous.get('visual_language') if previous else None)


