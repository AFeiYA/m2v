    layout: Literal['hero-stack', 'center-stack', 'staggered', 'right-stack'] = 'hero-stack'
    intent: str = Field(min_length=1, max_length=300)
    background: str = Field(pattern=r'^#[0-9a-fA-F]{6}$')
    accent: str = Field(pattern=r'^#[0-9a-fA-F]{6}$')
    motif: Literal['none', 'rings'] = 'none'
    visibility: Literal['cumulative'] = 'cumulative'
    final_hold: Literal['available-tail'] = 'available-tail'
    transition_out: Literal['cut', 'fade'] = 'cut'
    transition_note: str = Field(default='', max_length=300)
    nodes: list[PosterNode] = Field(min_length=1, max_length=12)
    visual_intensity: Literal['auto', 'restrained', 'expanded', 'peak'] = 'auto'
