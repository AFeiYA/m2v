class PhrasePlan(BaseModel):
    model_config = ConfigDict(extra='forbid')
    text: str = Field(min_length=1)
    word_indices: list[StrictInt] = Field(min_length=1)
    action: Literal['reveal', 'push', 'settle', 'hold'] = 'hold'
    emphasis: str = ''
    intensity: float = Field(default=.5, ge=0, le=1)


class PosterNode(BaseModel):
    """Semantic blocks, never geometry generated by a language model."""
    model_config = ConfigDict(extra='forbid')
    text: str = Field(min_length=1, max_length=300)
    word_indices: list[StrictInt] = Field(default_factory=list)
    role: Literal['primary', 'secondary', 'support'] = 'secondary'
    emphasis: str = Field(default='', max_length=100)
    color_role: Literal['foreground', 'accent', 'muted'] = 'foreground'
    hold: Literal['none', 'drift'] = 'none'
    beat_reaction: Literal['none', 'pulse'] = 'none'
    entrance: Literal['none', 'fade', 'slide-up', 'slide-left', 'scale-in'] = 'fade'
    settle_fraction: float = Field(default=.25, ge=.05, le=.5, allow_inf_nan=False)


class PosterRelation(BaseModel):
    """References semantic blocks; does not introduce a second lyric segmentation."""
    model_config = ConfigDict(extra='forbid')
    kind: Literal['guidance', 'contrast', 'negation', 'repetition', 'spatial']
    node_indices: list[StrictInt] = Field(min_length=1, max_length=12)
    intent: str = Field(min_length=1, max_length=300)


